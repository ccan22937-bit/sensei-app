export const getLocalizedPronunciation = (pronunciation: string, nativeLanguage: string): string => {
  const langKey = nativeLanguage.charAt(0).toUpperCase() + nativeLanguage.slice(1).toLowerCase();
  
  // Special fallbacks
  if (langKey === 'İspanyolca') return pronunciation;
  if (langKey === 'İbranice') return pronunciation;
  if (langKey === 'İtalyanca') return pronunciation;
  
  const translations = pronunciationTranslations[langKey];
  if (translations && translations[pronunciation]) {
    return translations[pronunciation];
  }
  return pronunciation;
};
